"""Protocolos (interfaces) de los repositorios.

Los servicios dependen de estos contratos, no de SQLAlchemy. Así se cumple
ISP (interfaces pequeñas y enfocadas) y DIP (dependencias hacia abstracciones).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date
from typing import Any, Protocol, Sequence

from app.catalog_specs import CatalogSpec
from app.models import (
    Alert,
    AuditLog,
    Carrier,
    Company,
    CostConcept,
    CostScenario,
    Currency,
    Document,
    DocumentType,
    Incoterm,
    Invoice,
    Operation,
    OperationItem,
    Payment,
    Port,
    Product,
    Shipment,
    User,
)
from app.schemas import (
    CostScenarioItemCreate,
    DocumentCreate,
    DocumentUpdate,
    InvoiceCreate,
    OperationCreate,
    OperationItemCreate,
    OperationUpdate,
    PaymentCreate,
    ShipmentCreate,
    ShipmentUpdate,
)


@dataclass
class OperationFilters:
    q: str = ""
    status: str = ""
    type: str = ""
    company_id: int | None = None


@dataclass
class DocumentFilters:
    q: str = ""
    status: str = ""
    operation_id: int | None = None


@dataclass
class InvoiceFilters:
    q: str = ""
    status: str = ""
    operation_id: int | None = None


@dataclass
class AlertFilters:
    status: str = "OPEN"
    severity: str = ""
    operation_id: int | None = None


@dataclass
class AuditFilters:
    q: str = ""
    action: str = ""
    entity: str = ""


@dataclass
class ChecklistEntry:
    document_type: DocumentType
    document: Document | None
    status: str
    is_complete: bool
    expiry_date: date | None = None


class OperationReader(Protocol):
    def list(self, filters: OperationFilters | None = None) -> Sequence[Operation]: ...
    def get(self, operation_id: int) -> Operation | None: ...
    def get_by_code(self, code: str) -> Operation | None: ...
    def list_assignable_users(self) -> Sequence[User]: ...
    def list_companies(self) -> Sequence[Company]: ...
    def list_ports(self) -> Sequence[Port]: ...
    def list_currencies(self) -> Sequence[Currency]: ...
    def list_incoterms(self) -> Sequence[Incoterm]: ...
    def list_products(self) -> Sequence[Product]: ...
    def list_document_types(self) -> Sequence[DocumentType]: ...
    def list_carriers(self) -> Sequence[Carrier]: ...
    def list_cost_concepts(self) -> Sequence[CostConcept]: ...
    def list_for_user(self, user_id: int) -> Sequence[Operation]: ...


class OperationWriter(Protocol):
    def create(self, data: OperationCreate, changed_by_id: int | None = None) -> Operation: ...
    def update(self, operation_id: int, data: OperationUpdate, changed_by_id: int | None = None) -> Operation: ...
    def delete(self, operation_id: int) -> None: ...
    def add_item(self, operation_id: int, data: OperationItemCreate) -> OperationItem: ...
    def remove_item(self, operation_id: int, item_id: int) -> None: ...
    def change_status(
        self, operation_id: int, new_status: str, changed_by_id: int | None, note: str | None = None
    ) -> Operation: ...


class CatalogRepository(Protocol):
    def list(self, spec: CatalogSpec, q: str = "") -> Sequence[Any]: ...
    def get(self, spec: CatalogSpec, entity_id: int) -> Any | None: ...
    def save(self, spec: CatalogSpec, values: dict[str, Any], entity_id: int | None = None) -> Any: ...
    def delete(self, spec: CatalogSpec, entity_id: int) -> None: ...
    def options(self, source: str) -> list[tuple[str, str]]: ...
    def count(self, spec: CatalogSpec) -> int: ...


class CostRepository(Protocol):
    def list_by_operation(self, operation_id: int) -> Sequence[CostScenario]: ...
    def get(self, scenario_id: int) -> CostScenario | None: ...
    def create(self, operation_id: int, name: str, description: str | None) -> CostScenario: ...
    def add_item(self, scenario_id: int, data: CostScenarioItemCreate, amount: Any, sort_order: int) -> CostScenario: ...
    def delete_item(self, item_id: int) -> CostScenario | None: ...
    def select(self, scenario_id: int) -> CostScenario: ...
    def delete(self, scenario_id: int) -> None: ...
    def product_subtotal(self, operation_id: int) -> Any: ...


class DocumentRepository(Protocol):
    def list(self, filters: DocumentFilters | None = None) -> Sequence[Document]: ...
    def get(self, document_id: int) -> Document | None: ...
    def create(self, data: DocumentCreate, uploaded_by_id: int | None = None) -> Document: ...
    def update(self, document_id: int, data: DocumentUpdate) -> Document: ...
    def delete(self, document_id: int) -> None: ...
    def checklist(self, operation_id: int) -> list[ChecklistEntry]: ...
    def pending_count(self) -> int: ...


class BillingRepository(Protocol):
    def list(self, filters: InvoiceFilters | None = None) -> Sequence[Invoice]: ...
    def get(self, invoice_id: int) -> Invoice | None: ...
    def create(self, data: InvoiceCreate) -> Invoice: ...
    def delete(self, invoice_id: int) -> None: ...
    def add_payment(self, data: PaymentCreate) -> Payment: ...
    def delete_payment(self, payment_id: int) -> None: ...
    def refresh_status(self, invoice_id: int) -> Invoice: ...


class LogisticsRepository(Protocol):
    def list(self) -> Sequence[Shipment]: ...
    def get(self, shipment_id: int) -> Shipment | None: ...
    def get_by_operation(self, operation_id: int) -> Shipment | None: ...
    def create(self, data: ShipmentCreate) -> Shipment: ...
    def update(self, shipment_id: int, data: ShipmentUpdate) -> Shipment: ...
    def delete(self, shipment_id: int) -> None: ...


class AlertRepository(Protocol):
    def list(self, filters: AlertFilters | None = None) -> Sequence[Alert]: ...
    def get(self, alert_id: int) -> Alert | None: ...
    def upsert(self, fingerprint: str, values: dict[str, Any]) -> Alert: ...
    def resolve(self, alert_id: int, user_id: int | None) -> Alert: ...
    def open_count(self) -> int: ...


class AuditRepository(Protocol):
    def log(
        self,
        user_id: int | None,
        action: str,
        entity: str,
        entity_id: int | None = None,
        detail: str | None = None,
    ) -> AuditLog: ...
    def list(self, filters: AuditFilters | None = None, limit: int = 200) -> Sequence[AuditLog]: ...


class DashboardRepository(Protocol):
    def summary(self, user_id: int | None = None) -> dict[str, Any]: ...
    def operations_by_status(self, user_id: int | None = None) -> list[dict[str, Any]]: ...
    def operations_by_type(self, user_id: int | None = None) -> list[dict[str, Any]]: ...
    def recent_operations(
        self, limit: int = 6, user_id: int | None = None
    ) -> Sequence[Operation]: ...
    def top_products(
        self, limit: int = 5, user_id: int | None = None
    ) -> list[dict[str, Any]]: ...
    def upcoming_shipments(
        self, limit: int = 5, user_id: int | None = None
    ) -> Sequence[Shipment]: ...
    def open_alerts(self, limit: int = 6, user_id: int | None = None) -> Sequence[Alert]: ...
